SELECT 
U.NAMESURNAME, COUNT(A.ID) AS ADRESSAYISI, COUNT(DISTINCT CT.ID) AS TEKILSEHIRSAYISI, COUNT(DISTINCT C.ID) AS TEKILULKESAYISI
FROM USERS U, ADDRESS A, COUNTRIES C, CITIES CT, TOWNS T, DISTRICTS D
WHERE U.ID = A.USERID AND C.ID = A.COUNTRYID
AND CT.ID = A.CITTYID AND T.ID = A.TOWNID
AND  A.DISTRICT = D.ID

GROUP BY U.NAMESURNAME 
HAVING COUNT(A.ID)>2

