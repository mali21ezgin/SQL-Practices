SELECT 
CT.CITY AS SEHIR,
COUNT(U.ID) AS KULLANICISAYISI, COUNT(D.ID) AS ILCESAYISI, COUNT(T.ID) SEMTSAYISI
FROM USERS U, ADDRESS A, COUNTRIES C, CITIES CT, TOWNS T, DISTRICTS D
WHERE U.ID = A.USERID AND C.ID = A.COUNTRYID
AND CT.ID = A.CITTYID AND T.ID = A.TOWNID
AND  A.DISTRICT = D.ID
GROUP BY CT.CITY 

