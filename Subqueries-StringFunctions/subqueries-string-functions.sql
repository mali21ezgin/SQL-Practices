SELECT 
ID, COUNTRY,
SUBSTRING(COUNTRY,LEN(COUNTRY),1) AS SONHARF
FROM COUNTRIES
WHERE SUBSTRING(COUNTRY,LEN(COUNTRY),1) = 'A'
ORDER BY COUNTRY ASC

