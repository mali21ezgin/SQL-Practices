SELECT
ID,ADDRESSTEXT,
LEFT(ADDRESSTEXT,CHARINDEX(' ',ADDRESSTEXT) - 1) AS ILKPARCA,
RIGHT(ADDRESSTEXT, LEN(ADDRESSTEXT) - CHARINDEX(' ',ADDRESSTEXT)) AS KALANPARCA
FROM ADDRESS
WHERE CHARINDEX(' ', ADDRESSTEXT) > 0

