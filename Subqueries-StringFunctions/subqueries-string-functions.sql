--Question-1
SELECT BRAND AS MARKA ,
MIN(UNITPRICE) AS ENDUSUKFIYAT,
MAX(UNITPRICE) AS ENYUKSEKFIYAT,
AVG(UNITPRICE) AS ORTALAMAFIYAT,
COUNT(*) URUNSAYISI
FROM ITEMS 
GROUP BY BRAND
ORDER BY AVG(UNITPRICE) DESC

