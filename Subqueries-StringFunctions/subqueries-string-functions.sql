(SELECT AVG(UNITPRICE)  FROM ITEMS I2 WHERE I.BRAND = I2.BRAND) AS MARKAORTALAMAFIYAT
FROM ITEMS I

--Question-3
SELECT DISTINCT 
    A.USERID,
    (
        SELECT TOP 1 A2.ADDRESSTEXT
        FROM ADDRESS A2
        WHERE A2.USERID = A.USERID
        ORDER BY A2.ID ASC
    ) AS ILKADRES,
    (
        SELECT TOP 1 A2.ADDRESSTEXT
        FROM ADDRESS A2
        WHERE A2.USERID = A.USERID
        ORDER BY A2.ID DESC
    ) AS SONADRES,
    (
        SELECT COUNT(A2.ADDRESSTEXT)
        FROM ADDRESS A2
        WHERE A2.USERID = A.USERID
    ) AS ADRESSAYISI
FROM ADDRESS A
ORDER BY A.USERID ASC;

