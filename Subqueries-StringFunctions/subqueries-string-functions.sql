SELECT 
LEN(ITEMNAME) AS ORIJINALUZUNLUK,
LTRIM(ITEMNAME) AS SOLKIRPILMIS,
RTRIM(ITEMNAME) AS SAGKIRPILMIS,
TRIM(ITEMNAME) AS TAMKIRPILMIS,
LEN(TRIM(ITEMNAME)) KIRPILMISUZUNLUK
 FROM ITEMS
WHERE LEN(ITEMNAME) <> LEN(TRIM(ITEMNAME))

--Question-8
SELECT 
A.ID,
CONCAT(CT.COUNTRY, ' ', C.CITY, ' ',D.DISTRICT, ' ',A.POSTALCODE) AS BIRLESTIRILMIS_CONCAT,
CONCAT_WS(' ',CT.COUNTRY, C.CITY,D.DISTRICT,A.POSTALCODE) AS BIRLESTIRILMIS_CONCAT_WS
 FROM ADDRESS A
INNER JOIN COUNTRIES CT ON CT.ID = A.COUNTRYID
INNER JOIN CITIES C ON C.ID = A.CITYID
INNER JOIN DISTRICTS D ON D.ID = A.DISTRICTID

