CREATE DATABASE FieldServiceDB

USE FieldServiceDB

CREATE TABLE USERS(
USERID INT IDENTITY(1,1),
FULLNAME NVARCHAR(100) NOT NULL,
EMAIL NVARCHAR(150) NOT NULL UNIQUE,
PHONE NVARCHAR(20) NULL,
ROLE_ VARCHAR(20) NOT NULL,
ISACTIVE BIT NOT NULL DEFAULT 1,
CREATEDAT DATETIME NOT NULL DEFAULT SYSDATETIME(),
CONSTRAINT [PK_USERS] PRIMARY KEY CLUSTERED ([USERID] ASC),
CONSTRAINT [CK_USERS_ROLE] CHECK (ROLE_ IN ('Customer', 'Operator', 'Technician'))
)

CREATE TABLE LOCATIONS(
LOCATIONID INT IDENTITY(1,1) NOT NULL,
CITY NVARCHAR(60) NOT NULL,
DISTRICT NVARCHAR(60) NOT NULL,
NEIGHBORHOOD NVARCHAR(80) NULL,
ADDRESSLINE NVARCHAR(250) NOT NULL,
POSTALCODE VARCHAR(10) NULL,
ISACTIVE BIT NOT NULL,
CONSTRAINT [PK_LOCATIONS] PRIMARY KEY CLUSTERED ([LOCATIONID] ASC))

CREATE TABLE ASSETS(
ASSETID INT IDENTITY(1,1) NOT NULL,
LOCATIONID INT NOT NULL,
ASSETCODE VARCHAR(40) NOT NULL,
ASSETNAME NVARCHAR(120) NOT NULL,
ASSETTYPE NVARCHAR(50) NOT NULL,
INSTALLEDDATE DATE NULL,
ISACTIVE BIT NOT NULL DEFAULT 1,
CONSTRAINT [PK_ASSETS] PRIMARY KEY CLUSTERED ([ASSETID] ASC ),
CONSTRAINT [UQ_ASSETS_ASSETCODE] UNIQUE ([ASSETCODE]),
CONSTRAINT [FK_ASSETS_LOCATIONS] FOREIGN KEY ([LOCATIONID]) REFERENCES dbo.LOCATIONS ([LOCATIONID]))

CREATE TABLE CATEGORIES(
CATEGORYID INT IDENTITY(1,1) NOT NULL,
CATEGORYNAME NVARCHAR(80) NOT NULL,
SLAHOURS INT NOT NULL,
ISACTIVE BIT NOT NULL DEFAULT 1,
CONSTRAINT [PK_CATEGORIES] PRIMARY KEY CLUSTERED ([CATEGORYID] ASC),
CONSTRAINT [UQ_CATEGORIES_CATEGORYNAME] UNIQUE ([CATEGORYNAME]),
CONSTRAINT [CK_CATEGORIES_SLAHOURS] CHECK ([SLAHOURS]> 0))

CREATE TABLE TICKETS(
TICKETID INT IDENTITY(1,1) NOT NULL,
USERID INT NOT NULL,
ASSETID INT NOT NULL,
CATEGORYID INT NOT NULL,
TITLE NVARCHAR(150) NOT NULL,
DESCRIPTION_ NVARCHAR(MAX) NULL,
PRIORITY_ NVARCHAR(15) NOT NULL DEFAULT 'Medium',
STATUS_ VARCHAR(20) NOT NULL DEFAULT  'Open',
CREATEDAT DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
RESOLVEDAT DATETIME2 NULL,
CONSTRAINT [PK_TICKETS] PRIMARY KEY CLUSTERED ([TICKETID] ASC),
CONSTRAINT [FK_TICKETS_USERS] FOREIGN KEY ([USERID]) REFERENCES dbo.USERS ([USERID]),
CONSTRAINT [FK_TICKETS_ASSETS] FOREIGN KEY ([ASSETID]) REFERENCES dbo.ASSETS ([ASSETID]),
CONSTRAINT [FK_TICKETS_CATEGORIES] FOREIGN KEY ([CATEGORYID]) REFERENCES dbo.CATEGORIES ([CATEGORYID]),

CONSTRAINT [CK_TICKETS_PRIORITY_] CHECK ([PRIORITY_] IN  ('Low', 'Medium', 'High', 'Critical')),
CONSTRAINT [CK_TICKETS_STATUS_] CHECK ([STATUS_] IN  ('Open', 'Assigned', 'InProgress', 'Resolved', 'Closed')))

CREATE TABLE TICKETASSIGNMENTS(
ASSIGNMENTID INT IDENTITY(1,1) NOT NULL,
TICKETID INT NOT NULL,
TECHNICIANID INT NOT NULL,
ASSEIGNEDAT DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
STATUSAFTERASSIGNMENT VARCHAR(20) NOT NULL DEFAULT 'Assigned',
NOTES NVARCHAR(300) NULL ,
CONSTRAINT [PK_TICKETASSIGNMENTS] PRIMARY KEY CLUSTERED ([ASSIGNMENTID] ASC),
CONSTRAINT [FK_TICKETASSIGNMENTS_TICKETS] FOREIGN KEY ([TICKETID]) REFERENCES dbo.TICKETS ([TICKETID]),  
CONSTRAINT [FK_TICKETASSIGNMENTS_USERS] FOREIGN KEY ([TECHNICIANID]) REFERENCES dbo.USERS ([USERID]),  
CONSTRAINT [CK_TICKETASSIGNMENTS_STATUSAFTERASSIGNMENT] CHECK ([STATUSAFTERASSIGNMENT] IN ('Assigned', 'InProgress', 'Resolved', 'Closed')))


