SELECT TOP 5 CITY, 
SUM(SALES) AS TOTALSALES,
COUNT(DISTINCT CUSTOMER_ID) UNIQUE_CUSTOMERS,
COUNT(*) RAW_COUNT
FROM RAW_SUPERSTORE
GROUP BY CITY 
ORDER BY SUM(SALES) DESC

