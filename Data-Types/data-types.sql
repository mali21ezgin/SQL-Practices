SELECT CITY,
COUNT(DISTINCT ORDER_ID) UNIQUE_ORDERS,
COUNT(DISTINCT CUSTOMER_ID) UNIQUE_CUSTOMERS,
COUNT(*) ROW_COUNT
FROM RAW_SUPERSTORE
WHERE MONTH_NAME = '01.OCAK'
GROUP BY CITY
ORDER BY CITY

